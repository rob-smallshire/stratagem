def miner_source() -> str:
    """The miner's light window, nearest first: each entry's offset from the
    miner, its neighbours one step nearer (lighting.miner_predecessors), and
    the entry at each offset, by (dy + MINER_RADIUS) * MINER_SPAN + dx +
    MINER_RADIUS."""
    order = lighting.MINER_ORDER
    radius, span = lighting.MINER_RADIUS, 2 * lighting.MINER_RADIUS + 1
    predecessors = [lighting.miner_predecessors(k) for k in range(len(order))]
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/lighting.py", ""]
    for name, values in [
        ("miner_dx", [dx & 0xFF for dx, _ in order]),
        ("miner_dy", [dy & 0xFF for _, dy in order]),
        ("miner_across", [p[0] for p in predecessors]),
        ("miner_vertical", [p[1] for p in predecessors]),
        ("miner_diagonal", [p[2] for p in predecessors]),
        ("miner_index", [lighting.MINER_INDEX[(dx, dy)] for dy in range(-radius, radius + 1)
                         for dx in range(-radius, radius + 1)]),
    ]:
        lines.append(f".{name}")
        lines += _bytes_lines(values)
    lines.append(".times_span")
    lines += _bytes_lines([n * span for n in range(span)])
    return "\n".join(lines) + "\n"


SMOOTH_GRID_RADIUS = lighting.MINER_RADIUS + 1     # the window, and a dark border
SMOOTH_GRID_SPAN = 2 * SMOOTH_GRID_RADIUS + 1


def _tile_index(dx: int, dy: int) -> int:
    """A tile's index in sl_tile_excess (and sl_across_left/right): row-major
    over the window and its border."""
    return (dy + SMOOTH_GRID_RADIUS) * SMOOTH_GRID_SPAN + dx + SMOOTH_GRID_RADIUS


SMOOTH_RADIAL_ROWS = 96        # |dy| in lines: a pass never looks further (92)
SMOOTH_RADIAL_COLUMNS = 128    # dx + 64 in pixels


def smooth_radial() -> bytes:
    """The smooth miner's light on open ground, rounded: at |dy| * 128 +
    dx + 64, for a cell centre dx pixels across and dy lines down from the
    middle of the miner's box."""
    return bytes(lighting.rounded(lighting.radial_level(dx - SMOOTH_RADIAL_COLUMNS // 2, dy))
                 for dy in range(SMOOTH_RADIAL_ROWS) for dx in range(SMOOTH_RADIAL_COLUMNS))


# The parasite's radial table (asm/miner_light.asm), packed. A pass reads it
# only for blocks of tiles within GRID_RADIUS of the miner's tile; outside
# the pool's window (MINER_RADIUS) a block's excess is FAR, which darkens it
# whatever it reads. So only offsets a window block can have must be exact:
# 8 ox + 2 + 4 b - mxr across and 16 oy + 8 j + 4 - myr down (mxr 0-7, myr
# 0-15). Rows are packed so that their zeros overlap; each row's dx = 0 is
# found from a table by |dy|, up to the furthest a pass reads.
RADIAL_EXACT_ACROSS = 8 * lighting.MINER_RADIUS + 6     # |dx|, pixels
RADIAL_EXACT_DOWN = 16 * lighting.MINER_RADIUS + 12     # |dy|, lines
RADIAL_ROWS_READ = 16 * (lighting.MINER_RADIUS + 1) + 12 + 1


def packed_radial() -> tuple[bytes, list[int]]:
    """The radial table's rows for |dy| up to RADIAL_EXACT_DOWN, each exact
    for |dx| up to RADIAL_EXACT_ACROSS, overlapping where they agree; and
    for each |dy| a pass reads, the offset of its row's dx = 0."""
    table: list[int | None] = []
    centres = []
    for dy in range(RADIAL_EXACT_DOWN + 1):
        row = [lighting.rounded(lighting.radial_level(dx, dy))
               for dx in range(-RADIAL_EXACT_ACROSS, RADIAL_EXACT_ACROSS + 1)]
        offset = next(o for o in range(len(table) + 1)
                      if all(o + i >= len(table) or table[o + i] == v for i, v in enumerate(row)))
        table += [None] * (offset + len(row) - len(table))
        table[offset:offset + len(row)] = row
        centres.append(offset + RADIAL_EXACT_ACROSS)
    centres += [centres[-1]] * (RADIAL_ROWS_READ - len(centres))     # read, but always dark
    return bytes(table), centres


def radial_rows_source() -> str:
    """The address of each packed row's dx = -RADIAL_CENTRE (where a pass's
    radial column 0 reads), by |dy|: assembled after sl_radial."""
    _, centres = packed_radial()
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/lighting.py", ""]
    for name, part in (("sl_radial_row_lo", "LO"), ("sl_radial_row_hi", "HI")):
        lines.append(f".{name}")
        lines += [f"    EQUB {part}(sl_radial + {centre} - RADIAL_CENTRE)" for centre in centres]
    return "\n".join(lines) + "\n"


SMOOTH_REACH_ROWS = 64        # lines: beyond, the light never reaches


def _reach(dy: int) -> int:
    """How many pixels across the light reaches at dy lines from the middle
    of the miner's box: beyond, the open-ground level is below 0."""
    return max(dx for dx in range(64) if lighting.radial_level(dx, dy) >= 0)


GRAPHICS_SLOTS = 32            # cell graphics in a material's page


def _cell_visibility(cell: bytes, parity: int) -> int:
    """A cell's 8 bytes drawn in a cell of `parity`: a bit per Bayer
    threshold (in order) that falls on a pixel of colour."""
    order = lighting.parity_thresholds(parity)
    bits = 0
    for line in range(lighting.CELL_LINES):
        for x, colour_bits in ((0, 0b00101010), (1, 0b00010101)):     # left, right: colour bits 0-2
            if cell[line] & colour_bits:
                bits |= 1 << order.index(int(lighting.BAYER[line % 4][2 * parity + x]))
    return bits


def _graphics_visibility(parity: int) -> list[int]:
    """For each cell graphic in the material pages (page material * 2 +
    background, then slot: offset / 8), its visibility (_cell_visibility)."""
    visibility = []
    for material in range(tiles.DRAWN_COUNT):
        graphics = tiles.material_pages(material)
        visibility += [_cell_visibility(graphics[n:n + 8], parity) for n in range(0, len(graphics), 8)]
    assert len(visibility) == tiles.DRAWN_COUNT * 2 * GRAPHICS_SLOTS
    return visibility


def _pair_visibility(parity: int) -> list[int]:
    """For each pair (piece index * 2 + backdrop), its eight cells'
    visibility, in the order of a slot's (half * 4 + column)."""
    visibility = []
    for material in tiles.PIECES:
        for backdrop in tiles.BACKDROPS:
            graphics = tiles.compose(material, backdrop)
            visibility += [_cell_visibility(graphics[n:n + 8], parity) for n in range(0, 64, 8)]
    return visibility


def _between(old: int, new: int, parity: int) -> int:
    low, high = sorted((lighting.mask_class(old, parity), lighting.mask_class(new, parity)))
    return (1 << high) - (1 << low)


def smooth_source() -> str:
    """Tables for the smooth miner's light: the pool on open ground (window
    order, as miner_light gives it with every tile clear), and for each
    parity, at old * 16 + new level, the thresholds whose pixels change;
    and how far across the light reaches at each distance down."""
    open_pool = lighting.miner_light(lambda x, y: True, 0, 0)
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/lighting.py", "",
             f"SMOOTH_REACH_ROWS = {SMOOTH_REACH_ROWS}", ""]
    for name, values in [
        ("smooth_open_pool", [open_pool[offset] for offset in lighting.MINER_ORDER]),
        ("smooth_reach", [_reach(dy) for dy in range(SMOOTH_REACH_ROWS)]),
        ("smooth_tile_index", [_tile_index(dx, dy) for dx, dy in lighting.MINER_ORDER]),
        ("smooth_graphics_even", _graphics_visibility(0)),
        ("smooth_graphics_odd", _graphics_visibility(1)),
        ("pair_visibility_even", _pair_visibility(0)),
        ("pair_visibility_odd", _pair_visibility(1)),
        ("smooth_between_even", [_between(old, new, 0) for old in range(16) for new in range(16)]),
        ("smooth_between_odd", [_between(old, new, 1) for old in range(16) for new in range(16)]),
    ]:
        lines.append(f".{name}")
        lines += _bytes_lines(values)
    return "\n".join(lines) + "\n"


def smooth_flood_source() -> str:
    """The smooth light's flood, unrolled (asm/smooth_light.asm falls into it
    from sl_flood): lighting.miner_light for each window entry in order, its
    neighbours one step nearer the miner at fixed addresses."""
    order = lighting.MINER_ORDER
    no = lighting.NO_TILE
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/lighting.py", "",
             "    LDA #MINER_LEVEL", "    STA sl_pool"]

    def candidate(lines, load, step, label):
        """Keep load - step as sl_best if not below zero and brighter."""
        lines += [f"    LDA {load}"]
        if step:
            lines += ["    SEC", f"    SBC #{step}", f"    BCC {label}"]
        lines += ["    CMP sl_best", f"    BCC {label}", "    STA sl_best", f".{label}"]

    for k in range(1, len(order)):
        across, vertical, diagonal = lighting.miner_predecessors(k)
        near = [p for p in (across, vertical) if p != no]
        lines += [f"{{                               \\ Entry {k}: {order[k]}", "    LDA #0", "    STA sl_best",
                  f"    LDA sl_pool_clear + {k}", "    BEQ wall"]
        for n, p in enumerate(near):        # into open ground
            lines += [f"    LDA sl_pool_clear + {p}", f"    BEQ open_skip{n}"]
            candidate(lines, f"sl_pool + {p}", "LIGHT_OPEN_STEP", f"open_skip{n}")
        if diagonal != no:                  # past an open corner
            lines += [f"    LDA sl_pool_clear + {diagonal}", "    BEQ diagonal_skip",
                      f"    LDA sl_pool_clear + {across}", f"    ORA sl_pool_clear + {vertical}",
                      "    BEQ diagonal_skip"]
            candidate(lines, f"sl_pool + {diagonal}", "LIGHT_OPEN_DIAGONAL_STEP", "diagonal_skip")
        lines += ["    JMP store", ".wall"]
        for n, p in enumerate(near):        # into a wall: a face from open ground, soaked from a wall
            lines += [f"    LDA sl_pool_clear + {p}", f"    BEQ from_wall{n}", f"    LDA sl_pool + {p}",
                      "    CMP sl_best", f"    BCC wall_skip{n}", "    STA sl_best", f"    BCS wall_skip{n}",
                      f".from_wall{n}"]
            candidate(lines, f"sl_pool + {p}", "LIGHT_WALL_STEP", f"wall_skip{n}")
        lines += [".store", "    LDA sl_best", f"    STA sl_pool + {k}", "}"]

    return "\n".join(lines) + "\n"


