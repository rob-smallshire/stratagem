def shapes_source() -> str:
    """The properties of materials and shapes, as labelled tables, INCLUDEd
    inline (not a macro, so that the labels are global)."""
    materials = range(tiles.MATERIAL_COUNT)
    shapes = range(tiles.MAX_SHAPES)
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/tiles.py and actions.py", ""]
    lines.append(".material_passable")
    lines += _bytes_lines([0xFF if m in tiles.PASSABLE else 0 for m in materials])
    lines.append(".material_empty")      # can be placed into
    lines += _bytes_lines([0xFF if m in actions.EMPTY else 0 for m in materials])
    lines.append(".material_quarters")   # quarters a dig removes; 0 if not diggable
    lines += _bytes_lines([actions.QUARTERS_PER_DIG.get(m, 0) for m in materials])
    # Solid quarter-cells of each shape, bit row * 4 + column.
    lines += _words("shape_mask", [tiles.SHAPES[s].mask if s < tiles.SHAPE_COUNT else 0 for s in shapes])
    lines.append(".shape_solid_count")    # quarter-cells solid in each shape
    lines += _bytes_lines([bin(tiles.SHAPES[s].mask).count("1") if s < tiles.SHAPE_COUNT else 0 for s in shapes])
    # What a dig of 1 or 2 quarters from each side leaves of each shape, by
    # side * MAX_SHAPES + shape (&FF: nothing). A dig of 4 leaves nothing.
    for quarters in (1, 2):
        lines.append(f".dig_{quarters}")
        lines += _bytes_lines([(lambda r: 0xFF if r is None else r)(tiles.dig_shape(shape, quarters, side))
                               if shape < tiles.SHAPE_COUNT else 0xFF
                               for side in range(4) for shape in shapes])
    # Each shape cut back to within each ramp (&FE: within it already, nothing
    # to cut; &FF: nothing left).
    for name in ("RAMP_TOP_LEFT", "RAMP_TOP_RIGHT"):
        ramp = getattr(world, name)
        lines.append(f".cut_{name.lower()}")
        lines += _bytes_lines([(lambda r: 0xFE if r is False else 0xFF if r is None else r)(tiles.cut_to(shape, ramp))
                               if shape < tiles.SHAPE_COUNT else 0xFE
                               for shape in shapes])
    # Quarter-cells a player box overlaps in a tile, by the box's position
    # relative to the tile, offset to be positive: columns by x + 8 (x in
    # -7..7), rows by y + 24 (y in -23..15).
    def columns_mask(rx: int) -> int:
        mask = 0
        for column in range(4):
            if rx < (column + 1) * tiles.QUARTER_PIXELS and rx + player.PLAYER_WIDTH > column * tiles.QUARTER_PIXELS:
                mask |= 0x1111 << column
        return mask

    def rows_mask(ry: int) -> int:
        mask = 0
        for row in range(4):
            if ry < (row + 1) * tiles.QUARTER_LINES and ry + player.PLAYER_HEIGHT > row * tiles.QUARTER_LINES:
                mask |= 0xF << (4 * row)
        return mask

    lines += _words("box_columns", [columns_mask(i - 8) for i in range(16)])
    lines += _words("box_rows", [rows_mask(i - 24) for i in range(40)])
    # Quarter-cells in columns c0..c1 (all rows), and in rows r0..r1 (all
    # columns), indexed by c0 * 4 + c1 (or r0 * 4 + r1); empty if c0 > c1.
    def column_span(index: int) -> int:
        c0, c1 = divmod(index, 4)
        return sum(0x1111 << c for c in range(c0, c1 + 1))

    def row_span(index: int) -> int:
        r0, r1 = divmod(index, 4)
        return sum(0xF << (4 * r) for r in range(r0, r1 + 1))

    lines += _words("column_span", [column_span(i) for i in range(16)])
    lines += _words("row_span", [row_span(i) for i in range(16)])
    lines.append(".lowest_bit")           # of a nibble; 4 if none
    lines += _bytes_lines([next((b for b in range(4) if n >> b & 1), 4) for n in range(16)])
    lines.append(".highest_bit")
    lines += _bytes_lines([next((b for b in range(3, -1, -1) if n >> b & 1), 4) for n in range(16)])
    lines.append(".surface_heights")      # for the background rule
    lines += _bytes_lines(world.HEIGHTS)
    return "\n".join(lines) + "\n"


