def pack_source() -> str:
    """The pack screen (pack.py): its constants, and, as macros of bytes,
    the icons of its own (pack.OWN_ICONS), each kind's icon's address, the
    digits and the arrowheads (and two blank cells, then a tool's
    arrowheads)."""
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/pack.py", ""]
    for name in ("INPUT_PACK", "KEY_CYCLE", "KEY_CELL", "KEY_CLEAR", "KEY_MAKE", "KEY_BOOK", "KEY_NEXT", "MAKE_DELAY",
                 "MAKE_REPEAT", "GRID_PITCH", "ROWS_PER_GRID_ROW", "BELT_SLOTS", "BELT_PITCH", "BELT_LEFT",
                 "ROWS_PER_BELT", "SHOW_TOOL", "PACK_COLUMNS", "SLOT_CELLS", "PANEL_LEFT", "PANEL_TOP", "PANEL_COLUMNS",
                 "ROWS_PER_SLOT_ROW"):
        lines.append(f"{name} = {getattr(pack, name)}")
    lines.append("")
    lines.append("MACRO PACK_ICONS")
    for kind in pack.OWN_ICONS:
        lines += _bytes_lines(pack.icon(kind))
    lines.append("ENDMACRO")
    lines.append("")
    addresses = []
    for kind in range(inventory.KIND_COUNT):
        if kind in pack.ICON_MATERIALS:
            material = pack.ICON_MATERIALS[kind]
            assert pack.icon(kind) == tiles.material_pages(material)[:screen.TILE_BYTES]
            addresses.append(f"material_pages + {material} * &200")
        else:
            addresses.append(f"pack_icons + {pack.OWN_ICONS.index(kind)} * {screen.TILE_BYTES}")
    for half in ("LO", "HI"):
        lines.append(f"MACRO PACK_ICON_{'LOW' if half == 'LO' else 'HIGH'}")
        lines += [f"    EQUB {half}({address})" for address in addresses]
        lines.append("ENDMACRO")
    lines.append("")
    lines.append("MACRO PACK_DIGITS")
    for d in range(10):
        lines += _bytes_lines(pack.digit(d))
    lines.append("ENDMACRO")
    lines.append("")
    lines.append("MACRO PACK_SOCKET")
    lines += _bytes_lines(pack.socket())
    lines.append("ENDMACRO")
    lines.append("")
    lines.append("MACRO GRID_LEFTS")
    lines += _bytes_lines([pack.grid_left(size) for size in range(crafting.GRID_MAX + 1)])
    lines.append("ENDMACRO")
    lines.append("")
    lines.append("MACRO PACK_MARKS")
    lines += _bytes_lines(pack.mark("right") + pack.mark("left") + pack.mark("blank") + pack.mark("blank")
                          + pack.mark("right", pack.TOOL_MARK_COLOUR) + pack.mark("left", pack.TOOL_MARK_COLOUR))
    lines.append("ENDMACRO")
    return "\n".join(lines) + "\n"


def crafting_source() -> str:
    """Crafting (crafting.py): its constants, and, as macros of bytes, each
    station's grid size and the recipes: by recipe, the shape's width,
    height, the kind made, how many and the station, and its first cell in
    the shapes, the cells of every recipe's shape by rows (CELL_EMPTY:
    none)."""
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/crafting.py", ""]
    for name, value in (("GRID_MAX", crafting.GRID_MAX), ("GRID_CELLS", crafting.GRID_CELLS),
                        ("CELL_EMPTY", crafting.EMPTY), ("STATION_HAND", crafting.STATION_HAND),
                        ("STATION_BENCH", crafting.STATION_BENCH), ("NEAR_ACROSS", crafting.NEAR_ACROSS),
                        ("NEAR_UP_DOWN", crafting.NEAR_UP_DOWN),
                        ("RECIPE_COUNT", len(crafting.RECIPES))):
        lines.append(f"{name} = {value}")
    lines.append("")
    shapes, firsts = [], []
    for recipe in crafting.RECIPES:
        firsts.append(len(shapes))
        shapes += [kind for row in recipe.rows for kind in row]
    assert len(shapes) < 0x100
    tables = {
        "GRID_SIZES": [crafting.GRID_SIZES[station] for station in range(len(crafting.GRID_SIZES))],
        "RECIPE_WIDTHS": [len(recipe.rows[0]) for recipe in crafting.RECIPES],
        "RECIPE_HEIGHTS": [len(recipe.rows) for recipe in crafting.RECIPES],
        "RECIPE_MAKES": [recipe.makes for recipe in crafting.RECIPES],
        "RECIPE_COUNTS": [recipe.count for recipe in crafting.RECIPES],
        "RECIPE_STATIONS": [recipe.station for recipe in crafting.RECIPES],
        "RECIPE_FIRSTS": firsts,
        "RECIPE_SHAPES": shapes,
    }
    for name, data in tables.items():
        lines.append(f"MACRO {name}")
        lines += _bytes_lines(data)
        lines.append("ENDMACRO")
        lines.append("")
    return "\n".join(lines)


