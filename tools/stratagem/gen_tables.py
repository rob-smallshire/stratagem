"""Generate assembler tables from their Python sources of truth.

Writes into build/generated/:
- tiles.asm: TILE_* material numbers, shape constants, the materials'
  graphics and the cell offsets of every shape;
- world.asm: the world generator's constants, HEIGHTS and PERM tables;
- camera.asm: the camera's and screen's constants;
- player.asm: the player's constants and sprite frames, and digging's;
- shapes.asm: the properties of materials and shapes, as labelled tables.
"""

from __future__ import annotations

from pathlib import Path

from stratagem import actions, camera, player, screen, sprites, tiles, world


def _bytes_lines(data: bytes | list[int], per_line: int = 16) -> list[str]:
    return [
        "    EQUB " + ", ".join(f"&{b:02X}" for b in data[i:i + per_line])
        for i in range(0, len(data), per_line)
    ]


def _words(name: str, values: list[int]) -> list[str]:
    return [f".{name}_low"] + _bytes_lines([v & 0xFF for v in values]) + \
           [f".{name}_high"] + _bytes_lines([v >> 8 for v in values])


def tiles_source() -> str:
    # The 6502 relies on this numbering: diggable materials GRASS to GEM,
    # and WATER and SKY, the last, passable along with AIR (asm/world.asm).
    assert tiles.DIGGABLE == list(range(tiles.GRASS, tiles.GEM + 1))
    assert tiles.PASSABLE == {tiles.AIR, tiles.WATER, tiles.SKY} and {tiles.WATER, tiles.SKY} == {7, 8}
    assert tiles.MATERIAL_COUNT == 9
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/tiles.py and world.py", ""]
    lines += [f"TILE_{name.upper()} = {number}" for number, name in enumerate(tiles.MATERIAL_NAMES)]
    lines.append(f"MATERIAL_COUNT = {tiles.MATERIAL_COUNT}")
    for name in ("SHAPE_FULL", "SHAPE_BITS", "BACKGROUND_SKY", "MAX_SHAPES", "QUARTERS"):
        lines.append(f"{name} = {getattr(tiles, name)}")
    for name in ("RAMP_TOP_LEFT", "RAMP_TOP_RIGHT", "RAMP_BOTTOM_LEFT", "RAMP_BOTTOM_RIGHT"):
        lines.append(f"SHAPE_{name} = {getattr(world, name)}")
    # Ramps for digging diagonally: down to the left is low on the left.
    lines.append(f"RAMP_DOWN_LEFT = {world.RAMP_TOP_LEFT}")
    lines.append(f"RAMP_DOWN_RIGHT = {world.RAMP_TOP_RIGHT}")
    lines.append(f"RAMP_UP_LEFT = {world.RAMP_TOP_RIGHT}")
    lines.append(f"RAMP_UP_RIGHT = {world.RAMP_TOP_LEFT}")
    lines.append("")
    lines.append("\\ Each material's graphics: a page of four cell variants for each background.")
    lines.append("MACRO MATERIAL_PAGES")
    for material in range(tiles.MATERIAL_COUNT):
        lines.append(f"    \\ {tiles.MATERIAL_NAMES[material]}")
        lines += _bytes_lines(tiles.material_pages(material))
    lines.append("ENDMACRO")
    lines.append("")
    lines.append("\\ The offset in its material's page of each cell (half * 4 + column) of")
    lines.append("\\ each shape: MAX_SHAPES entries per cell.")
    lines.append("MACRO CELL_OFFSETS")
    for cell in range(8):
        half, column = divmod(cell, 4)
        lines += _bytes_lines([tiles.cell_offset(shape, half, column) if shape < tiles.SHAPE_COUNT else 0
                               for shape in range(tiles.MAX_SHAPES)])
    lines.append("ENDMACRO")
    return "\n".join(lines) + "\n"


def world_source() -> str:
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/world.py", ""]
    for name in ("SOIL_DEPTH", "CAVE_THRESHOLD", "WATER_DEPTH", "ORE_THRESHOLD", "GEM_THRESHOLD",
                 "SLOT_COUNT"):
        lines.append(f"WORLD_{name} = {getattr(world, name)}")
    lines.append("")
    lines.append("MACRO WORLD_HEIGHTS")
    lines += _bytes_lines(world.HEIGHTS)
    lines.append("ENDMACRO")
    lines.append("")
    lines.append("MACRO WORLD_PERM")
    lines += _bytes_lines(world.PERM)
    lines.append("ENDMACRO")
    return "\n".join(lines) + "\n"


def camera_source() -> str:
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/camera.py and screen.py", ""]
    for name in ("VIEW_COLUMNS", "VIEW_ROWS"):
        lines.append(f"{name} = {getattr(screen, name)}")
    for name in ("CAMERA_X_MAX", "CAMERA_Y_MAX", "WINDOW_LEFT", "WINDOW_RIGHT",
                 "WINDOW_TOP", "WINDOW_BOTTOM", "LEAD_MAX", "MAX_STEP_X", "CENTRE_X", "CENTRE_Y",
                 "INPUT_LEFT", "INPUT_RIGHT", "INPUT_UP", "INPUT_DOWN", "INPUT_ACTION", "INPUT_PLACE"):
        lines.append(f"{name} = {getattr(camera, name)}")
    return "\n".join(lines) + "\n"


def player_source() -> str:
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/player.py and sprites.py", ""]
    for name in ("PLAYER_WIDTH", "PLAYER_HEIGHT", "TILE_WIDTH", "TILE_HEIGHT", "WALK_SPEED",
                 "GROUND_ACCELERATION", "AIR_ACCELERATION", "JUMP_SPEED", "AIR_JUMP_SPEED", "GRAVITY",
                 "MAX_FALL", "SNAP_DOWN", "ABILITY_DOUBLE_JUMP", "STARTING_ABILITIES"):
        lines.append(f"{name} = {getattr(player, name)}")
    for name in ("SPRITE_COLUMNS", "SPRITE_BYTES", "STAND", "WALK1", "WALK2", "JUMP", "LEFT_FACING"):
        lines.append(f"{name} = {getattr(sprites, name)}")
    start_px = 128 * player.TILE_WIDTH + 1
    start_py = world.HEIGHTS[128] * player.TILE_HEIGHT - player.PLAYER_HEIGHT
    lines.append(f"PLAYER_START_X = {start_px * player.SUBPIXELS}")
    lines.append(f"PLAYER_START_Y = {start_py * player.SUBPIXELS}")
    frames = sprites.sprite_frames()
    lines.append(f"SPRITE_FRAME_COUNT = {len(frames)}")
    lines.append("")
    lines.append("MACRO SPRITE_FRAMES")
    for number, data in enumerate(frames):
        lines.append(f"    \\ frame {number}")
        lines += _bytes_lines(data)
    lines.append("ENDMACRO")
    lines.append("")
    lines.append("")
    for name in ("PLACE_FRAMES", "INVENTORY_MAX", "DIG_FRAMES"):
        lines.append(f"{name} = {getattr(actions, name)}")
    lines.append(f"PLACED_TILE = {actions.PLACED_TILE}")
    for name in ("FROM_LEFT", "FROM_RIGHT", "FROM_TOP", "FROM_BOTTOM"):
        lines.append(f"{name} = {getattr(tiles, name)}")
    return "\n".join(lines) + "\n"


def shapes_source() -> str:
    """The properties of materials and shapes, as labelled tables, INCLUDEd
    inline (not a macro, so that the labels are global)."""
    materials = range(tiles.MATERIAL_COUNT)
    shapes = range(tiles.MAX_SHAPES)
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/tiles.py and actions.py", ""]
    lines.append(".material_passable")
    lines += _bytes_lines([0xFF if m in tiles.PASSABLE else 0 for m in materials])
    lines.append(".material_empty")      # can be placed into
    lines += _bytes_lines([0xFF if m in actions.EMPTY else 0 for m in materials])
    lines.append(".material_quarters")   # quarters a dig removes; 0 if not diggable
    lines += _bytes_lines([actions.QUARTERS_PER_DIG.get(m, 0) for m in materials])
    # Solid quarter-cells of each shape, bit row * 4 + column.
    lines += _words("shape_mask", [tiles.SHAPES[s].mask if s < tiles.SHAPE_COUNT else 0 for s in shapes])
    # What a dig of 1 or 2 quarters leaves of each shape, eroding from its
    # own side (&FF: nothing); a whole tile is eroded from the dig's side,
    # given by the whole_dig tables. A dig of 4 quarters leaves nothing.
    for quarters in (1, 2):
        lines.append(f".shape_dig_{quarters}")
        lines += _bytes_lines([0xFF if s == 0 or s >= tiles.SHAPE_COUNT else
                               (lambda r: 0xFF if r is None else r)(tiles.dig_shape(s, quarters, 0))
                               for s in shapes])
        lines.append(f".whole_dig_{quarters}")
        lines += _bytes_lines([tiles.dig_shape(tiles.SHAPE_FULL, quarters, side) for side in range(4)])
    # Quarter-cells a player box overlaps in a tile, by the box's position
    # relative to the tile, offset to be positive: columns by x + 8 (x in
    # -7..7), rows by y + 24 (y in -23..15).
    def columns_mask(rx: int) -> int:
        mask = 0
        for column in range(4):
            if rx < (column + 1) * tiles.QUARTER_PIXELS and rx + player.PLAYER_WIDTH > column * tiles.QUARTER_PIXELS:
                mask |= 0x1111 << column
        return mask

    def rows_mask(ry: int) -> int:
        mask = 0
        for row in range(4):
            if ry < (row + 1) * tiles.QUARTER_LINES and ry + player.PLAYER_HEIGHT > row * tiles.QUARTER_LINES:
                mask |= 0xF << (4 * row)
        return mask

    lines += _words("box_columns", [columns_mask(i - 8) for i in range(16)])
    lines += _words("box_rows", [rows_mask(i - 24) for i in range(40)])
    # Quarter-cells in columns c0..c1 (all rows), and in rows r0..r1 (all
    # columns), indexed by c0 * 4 + c1 (or r0 * 4 + r1); empty if c0 > c1.
    def column_span(index: int) -> int:
        c0, c1 = divmod(index, 4)
        return sum(0x1111 << c for c in range(c0, c1 + 1))

    def row_span(index: int) -> int:
        r0, r1 = divmod(index, 4)
        return sum(0xF << (4 * r) for r in range(r0, r1 + 1))

    lines += _words("column_span", [column_span(i) for i in range(16)])
    lines += _words("row_span", [row_span(i) for i in range(16)])
    lines.append(".lowest_bit")           # of a nibble; 4 if none
    lines += _bytes_lines([next((b for b in range(4) if n >> b & 1), 4) for n in range(16)])
    lines.append(".highest_bit")
    lines += _bytes_lines([next((b for b in range(3, -1, -1) if n >> b & 1), 4) for n in range(16)])
    lines.append(".surface_heights")      # for the background rule
    lines += _bytes_lines(world.HEIGHTS)
    return "\n".join(lines) + "\n"


def generate_all(generated_dirpath: Path) -> None:
    generated_dirpath.mkdir(parents=True, exist_ok=True)
    (generated_dirpath / "tiles.asm").write_text(tiles_source())
    (generated_dirpath / "world.asm").write_text(world_source())
    (generated_dirpath / "camera.asm").write_text(camera_source())
    (generated_dirpath / "player.asm").write_text(player_source())
    (generated_dirpath / "shapes.asm").write_text(shapes_source())
