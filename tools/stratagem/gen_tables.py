"""Generate assembler tables from their Python sources of truth.

Writes into build/generated/:
- tiles.asm: TILE_* numbers and the tile graphics (64 bytes per tile);
- world.asm: the world generator's constants, HEIGHTS and PERM tables;
- camera.asm: the camera's and screen's constants;
- player.asm: the player's constants and sprite frames, and digging's;
- kinds.asm: the properties of each kind of tile, as labelled tables.
"""

from __future__ import annotations

from pathlib import Path

from stratagem import actions, camera, player, screen, sprites, tiles, world


def _bytes_lines(data: bytes | list[int], per_line: int = 16) -> list[str]:
    return [
        "    EQUB " + ", ".join(f"&{b:02X}" for b in data[i:i + per_line])
        for i in range(0, len(data), per_line)
    ]


def tiles_source() -> str:
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/tiles.py", ""]
    lines += [f"TILE_{name.upper()} = {number}" for number, name in enumerate(tiles.TILE_NAMES)]
    lines.append(f"TILE_COUNT = {len(tiles.TILE_NAMES)}")
    lines.append(f"KIND_COUNT = {tiles.KIND_COUNT}")
    lines.append("")
    lines.append("MACRO TILE_GRAPHICS")
    for kind, data in enumerate(tiles.tile_graphics()):
        material, direction, removed = tiles.kind_info(kind)
        lines.append(f"    \\ kind {kind}: {tiles.TILE_NAMES[material]}" + (f", {removed}/4 dug from side {direction}" if removed else ""))
        lines += _bytes_lines(data)
    lines.append("ENDMACRO")
    return "\n".join(lines) + "\n"


def world_source() -> str:
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/world.py", ""]
    for name in ("SOIL_DEPTH", "CAVE_THRESHOLD", "WATER_DEPTH", "ORE_THRESHOLD", "GEM_THRESHOLD",
                 "SLOT_COUNT"):
        lines.append(f"WORLD_{name} = {getattr(world, name)}")
    lines.append("")
    lines.append("MACRO WORLD_HEIGHTS")
    lines += _bytes_lines(world.HEIGHTS)
    lines.append("ENDMACRO")
    lines.append("")
    lines.append("MACRO WORLD_PERM")
    lines += _bytes_lines(world.PERM)
    lines.append("ENDMACRO")
    return "\n".join(lines) + "\n"


def camera_source() -> str:
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/camera.py and screen.py", ""]
    for name in ("VIEW_COLUMNS", "VIEW_ROWS"):
        lines.append(f"{name} = {getattr(screen, name)}")
    for name in ("CAMERA_X_MAX", "CAMERA_Y_MAX", "WINDOW_LEFT", "WINDOW_RIGHT",
                 "WINDOW_TOP", "WINDOW_BOTTOM", "LEAD_MAX", "MAX_STEP_X", "CENTRE_X", "CENTRE_Y",
                 "INPUT_LEFT", "INPUT_RIGHT", "INPUT_UP", "INPUT_DOWN"):
        lines.append(f"{name} = {getattr(camera, name)}")
    return "\n".join(lines) + "\n"


HIT_OFFSET = 64     # added to positions relative to a tile, to keep them positive


def player_source() -> str:
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/player.py and sprites.py", ""]
    for name in ("PLAYER_WIDTH", "PLAYER_HEIGHT", "TILE_WIDTH", "TILE_HEIGHT", "WALK_SPEED",
                 "GROUND_ACCELERATION", "AIR_ACCELERATION", "JUMP_SPEED", "AIR_JUMP_SPEED", "GRAVITY",
                 "MAX_FALL", "ABILITY_DOUBLE_JUMP", "STARTING_ABILITIES"):
        lines.append(f"{name} = {getattr(player, name)}")
    for name in ("SPRITE_COLUMNS", "SPRITE_BYTES", "STAND", "WALK1", "WALK2", "JUMP", "LEFT_FACING"):
        lines.append(f"{name} = {getattr(sprites, name)}")
    start_px = 128 * player.TILE_WIDTH + 1
    start_py = world.HEIGHTS[128] * player.TILE_HEIGHT - player.PLAYER_HEIGHT
    lines.append(f"PLAYER_START_X = {start_px * player.SUBPIXELS}")
    lines.append(f"PLAYER_START_Y = {start_py * player.SUBPIXELS}")
    frames = sprites.sprite_frames()
    lines.append(f"SPRITE_FRAME_COUNT = {len(frames)}")
    lines.append("")
    lines.append("MACRO SPRITE_FRAMES")
    for number, data in enumerate(frames):
        lines.append(f"    \\ frame {number}")
        lines += _bytes_lines(data)
    lines.append("ENDMACRO")
    lines.append("")
    lines.append("")
    for name in ("INPUT_ACTION", "INPUT_PLACE", "PLACE_FRAMES", "INVENTORY_MAX", "DIG_FRAMES"):
        lines.append(f"{name} = {getattr(actions, name)}")
    lines.append(f"PLACED_TILE = {actions.PLACED_TILE}")
    lines.append(f"HIT_OFFSET = {HIT_OFFSET}")
    for name in ("PARTIAL_BASE", "DIRECTIONS", "QUARTERS", "FROM_LEFT", "FROM_RIGHT", "FROM_TOP", "FROM_BOTTOM"):
        lines.append(f"{name} = {getattr(tiles, name)}")
    return "\n".join(lines) + "\n"


def kinds_source() -> str:
    """The properties of each kind of tile, as labelled tables, INCLUDEd
    inline (not a macro, so that the labels are global)."""
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/tiles.py and actions.py", ""]
    kinds = range(tiles.KIND_COUNT)
    rects = [tiles.kind_rect(kind) for kind in kinds]
    lines.append(".kind_passable")
    lines += _bytes_lines([0xFF if rect is None else 0 for rect in rects])
    for index, name in enumerate(("left", "right", "top", "bottom")):
        lines.append(f".kind_solid_{name}")
        lines += _bytes_lines([0 if rect is None else rect[index] for rect in rects])
    infos = [tiles.kind_info(kind) for kind in kinds]
    # Offset forms for find_hits: a box at (x, y) relative to the tile, plus
    # HIT_OFFSET, overlaps the solid part if left_bound < x < right_bound and
    # top_bound < y < bottom_bound.
    lines.append(".kind_left_bound")
    lines += _bytes_lines([0 if rect is None else rect[0] + HIT_OFFSET - player.PLAYER_WIDTH for rect in rects])
    lines.append(".kind_right_bound")
    lines += _bytes_lines([0 if rect is None else rect[1] + HIT_OFFSET for rect in rects])
    lines.append(".kind_top_bound")
    lines += _bytes_lines([0 if rect is None else rect[2] + HIT_OFFSET - player.PLAYER_HEIGHT for rect in rects])
    lines.append(".kind_bottom_bound")
    lines += _bytes_lines([0 if rect is None else rect[3] + HIT_OFFSET for rect in rects])
    lines.append(".kind_material")
    lines += _bytes_lines([info[0] for info in infos])
    lines.append(".kind_direction")
    lines += _bytes_lines([info[1] for info in infos])
    lines.append(".kind_removed")
    lines += _bytes_lines([info[2] for info in infos])
    lines.append(".kind_empty")
    lines += _bytes_lines([0xFF if kind in actions.EMPTY else 0 for kind in kinds])
    lines.append(".material_quarters")   # quarters a dig removes; 0 if not diggable
    lines += _bytes_lines([actions.QUARTERS_PER_DIG.get(m, 0) for m in range(len(tiles.TILE_NAMES))])
    lines.append(".material_slot")        # index in DIGGABLE
    lines += _bytes_lines([tiles.DIGGABLE.index(m) if m in tiles.DIGGABLE else 0 for m in range(len(tiles.TILE_NAMES))])
    return "\n".join(lines) + "\n"


def generate_all(generated_dirpath: Path) -> None:
    generated_dirpath.mkdir(parents=True, exist_ok=True)
    (generated_dirpath / "tiles.asm").write_text(tiles_source())
    (generated_dirpath / "world.asm").write_text(world_source())
    (generated_dirpath / "camera.asm").write_text(camera_source())
    (generated_dirpath / "player.asm").write_text(player_source())
    (generated_dirpath / "kinds.asm").write_text(kinds_source())
