"""Generate assembler tables from their Python sources of truth.

Writes into build/generated/:
- tiles.asm: TILE_* numbers and the tile graphics (64 bytes per tile);
- world.asm: the world generator's constants, HEIGHTS and PERM tables;
- camera.asm: the camera's and screen's constants.
"""

from __future__ import annotations

from pathlib import Path

from stratagem import camera, screen, tiles, world


def _bytes_lines(data: bytes | list[int], per_line: int = 16) -> list[str]:
    return [
        "    EQUB " + ", ".join(f"&{b:02X}" for b in data[i:i + per_line])
        for i in range(0, len(data), per_line)
    ]


def tiles_source() -> str:
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/tiles.py", ""]
    lines += [f"TILE_{name.upper()} = {number}" for number, name in enumerate(tiles.TILE_NAMES)]
    lines.append(f"TILE_COUNT = {len(tiles.TILE_NAMES)}")
    lines.append("")
    lines.append("MACRO TILE_GRAPHICS")
    for number, data in enumerate(tiles.tile_graphics()):
        lines.append(f"    \\ {tiles.TILE_NAMES[number]}")
        lines += _bytes_lines(data)
    lines.append("ENDMACRO")
    return "\n".join(lines) + "\n"


def world_source() -> str:
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/world.py", ""]
    for name in ("SOIL_DEPTH", "CAVE_THRESHOLD", "WATER_DEPTH", "ORE_THRESHOLD", "GEM_THRESHOLD"):
        lines.append(f"WORLD_{name} = {getattr(world, name)}")
    lines.append("")
    lines.append("MACRO WORLD_HEIGHTS")
    lines += _bytes_lines(world.HEIGHTS)
    lines.append("ENDMACRO")
    lines.append("")
    lines.append("MACRO WORLD_PERM")
    lines += _bytes_lines(world.PERM)
    lines.append("ENDMACRO")
    return "\n".join(lines) + "\n"


def camera_source() -> str:
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/camera.py and screen.py", ""]
    for name in ("VIEW_COLUMNS", "VIEW_ROWS"):
        lines.append(f"{name} = {getattr(screen, name)}")
    for name in ("CAMERA_X_MAX", "CAMERA_Y_MAX", "MARKER_COLUMNS", "MARKER_LINES", "FOCUS_X_MAX",
                 "FOCUS_Y_MAX", "FOCUS_SPEED_X", "FOCUS_SPEED_Y", "WINDOW_LEFT", "WINDOW_RIGHT",
                 "WINDOW_TOP", "WINDOW_BOTTOM", "LEAD_MAX", "MAX_STEP_X", "CENTRE_X", "CENTRE_Y",
                 "INPUT_LEFT", "INPUT_RIGHT", "INPUT_UP", "INPUT_DOWN"):
        lines.append(f"{name} = {getattr(camera, name)}")
    return "\n".join(lines) + "\n"


def generate_all(generated_dirpath: Path) -> None:
    generated_dirpath.mkdir(parents=True, exist_ok=True)
    (generated_dirpath / "tiles.asm").write_text(tiles_source())
    (generated_dirpath / "world.asm").write_text(world_source())
    (generated_dirpath / "camera.asm").write_text(camera_source())
