"""Generate assembler tables from their Python sources of truth.

Writes into build/generated/:
- tiles.asm: TILE_* material numbers, shape constants, the materials'
  graphics and the cell offsets of every shape;
- world.asm: the world generator's constants, HEIGHTS and PERM tables;
- camera.asm: the camera's and screen's constants;
- player.asm: the player's constants and sprite frames, and digging's;
- shapes.asm: the properties of materials and shapes, as labelled tables;
- light.asm: lighting's constants and the dither mask page;
- miner.asm: the miner's light window, as labelled tables;
- radial_packed.bin, radial_rows.asm: the parasite's radial table, packed,
  and its rows' addresses.
"""

from __future__ import annotations

from pathlib import Path

from stratagem import actions, camera, lighting, player, screen, sprites, support, tiles, world


def _bytes_lines(data: bytes | list[int], per_line: int = 16) -> list[str]:
    return [
        "    EQUB " + ", ".join(f"&{b:02X}" for b in data[i:i + per_line])
        for i in range(0, len(data), per_line)
    ]


def _words(name: str, values: list[int]) -> list[str]:
    return [f".{name}_low"] + _bytes_lines([v & 0xFF for v in values]) + \
           [f".{name}_high"] + _bytes_lines([v >> 8 for v in values])


def _symbol(name: str) -> str:
    """A material's name as part of an assembler symbol."""
    return name.upper().replace(", ", "_").replace(" ", "_")


def tiles_source() -> str:
    # The 6502 relies on this numbering: diggable materials GRASS to GEM;
    # WATER and SKY the last of the drawn materials, and passable along with
    # AIR (asm/world.asm: generate_material makes no pieces); the pieces
    # after them, passable, drawn only through slots; and the tree's parts
    # in order (world.tree_part).
    assert tiles.DIGGABLE == list(range(tiles.GRASS, tiles.GEM + 1))
    assert tiles.PASSABLE == {tiles.AIR, tiles.WATER, tiles.SKY, *tiles.PIECES}
    assert (tiles.WATER, tiles.SKY, tiles.DRAWN_COUNT, tiles.FIRST_PIECE) == (7, 8, 9, 9)
    assert tiles.PIECES == list(range(tiles.FIRST_PIECE, tiles.MATERIAL_COUNT))
    lines = ["\\ Generated by stratagem.gen_tables from tools/stratagem/tiles.py and world.py", ""]
    lines += [f"TILE_{_symbol(name)} = {number}" for number, name in enumerate(tiles.MATERIAL_NAMES)]
    lines.append(f"MATERIAL_COUNT = {tiles.MATERIAL_COUNT}")
    lines.append(f"DRAWN_COUNT = {tiles.DRAWN_COUNT}")
    for name in ("SHAPE_FULL", "SHAPE_BITS", "BACKGROUND_SKY", "MAX_SHAPES", "QUARTERS"):
        lines.append(f"{name} = {getattr(tiles, name)}")
    for name in ("RAMP_TOP_LEFT", "RAMP_TOP_RIGHT", "RAMP_BOTTOM_LEFT", "RAMP_BOTTOM_RIGHT"):
        lines.append(f"SHAPE_{name} = {getattr(world, name)}")
    # Ramps for digging diagonally: down to the left is low on the left.
    lines.append(f"RAMP_DOWN_LEFT = {world.RAMP_TOP_LEFT}")
    lines.append(f"RAMP_DOWN_RIGHT = {world.RAMP_TOP_RIGHT}")
    lines.append(f"RAMP_UP_LEFT = {world.RAMP_TOP_RIGHT}")
    lines.append(f"RAMP_UP_RIGHT = {world.RAMP_TOP_LEFT}")
    lines.append("")
    lines.append("\\ Each material's graphics: a page of four cell variants for each background.")
    lines.append("MACRO MATERIAL_PAGES")
    for material in range(tiles.DRAWN_COUNT):
        lines.append(f"    \\ {tiles.MATERIAL_NAMES[material]}")
        lines += _bytes_lines(tiles.material_pages(material))
    lines.append("ENDMACRO")
    lines.append("")
    lines.append("\\ The offset in its material's page of each cell (half * 4 + column) of")
    lines.append("\\ each shape: MAX_SHAPES entries per cell.")
    lines.append("MACRO CELL_OFFSETS")
    for cell in range(8):
        half, column = divmod(cell, 4)
        lines += _bytes_lines([tiles.cell_offset(shape, half, column)
                               if shape < tiles.SHAPE_COUNT or shape in tiles.SLOT_SHAPE_VARIANTS else 0
                               for shape in range(tiles.MAX_SHAPES)])
    lines.append("ENDMACRO")
    lines.append("")
    lines.append("\\ Pieces and the slots they are composed into (tiles.py).")
    for name in ("FIRST_PIECE", "PIECE_COUNT", "SLOT_MATERIAL", "SLOT_GROUPS", "SLOT_COUNT"):
        lines.append(f"{name} = {getattr(tiles, name)}")
    lines.append("MACRO SLOT_SHAPES")
    lines += _bytes_lines(tiles.SLOT_SHAPES)
    lines.append("ENDMACRO")
    lines.append("\\ Each piece's data and mask, 128 bytes; each backdrop's graphics, 64.")
    lines.append("MACRO PIECE_LIBRARY")
    for material in tiles.PIECES:
        lines.append(f"    \\ {tiles.MATERIAL_NAMES[material]}")
        lines += _bytes_lines(tiles.piece_graphics(material))
    lines.append("ENDMACRO")
    lines.append("MACRO BACKDROP_LIBRARY")
    for backdrop in tiles.BACKDROPS:
        lines.append(f"    \\ {tiles.MATERIAL_NAMES[backdrop]}")
        lines += _bytes_lines(tiles.backdrop_graphics(backdrop))
    lines.append("ENDMACRO")
    return "\n".join(lines) + "\n"


