"""Index a Level 7 style disassembly for quick navigation.

Level 7 disassemblies mark each routine or table with a line such as

    ; plot_tile_strip_loop                       # optional comment

followed by lines that begin with the address, such as `&1739 a9 00 ...`.
Section headings are text lines underlined with `=`. The index lists one
line per label or heading, in file order:

    &1739  L4087  plot_tile_strip_loop  # optional comment

so a label can be found with grep and opened at its line number.

    uv run python -m stratagem.index_disassembly docs/local/X.txt docs/reference/X-index.txt
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

LABEL_PATTERN = re.compile(r"^; ([a-z_][a-z_0-9]*(?: \+ \d+)?)\s*(?:#\s*(.*))?$")
ADDRESS_PATTERN = re.compile(r"^&([0-9a-f]{4}) ")
UNDERLINE_PATTERN = re.compile(r"^=+$")


def index_lines(lines: list[str]) -> list[str]:
    entries = []
    for i, line in enumerate(lines):
        line = line.rstrip()
        if UNDERLINE_PATTERN.match(line) and i > 0 and lines[i - 1].strip():
            entries.append(f"\n## {lines[i - 1].strip()}  L{i}")
            continue
        match = LABEL_PATTERN.match(line)
        if match is None:
            continue
        name, comment = match.groups()
        address = "?????"
        for following in lines[i + 1:i + 40]:
            address_match = ADDRESS_PATTERN.match(following)
            if address_match:
                address = "&" + address_match.group(1)
                break
        entry = f"{address}  L{i + 1}  {name}"
        if comment:
            entry += f"  # {comment.strip()}"
        entries.append(entry)
    return entries


def main() -> None:
    source_filepath, index_filepath = map(Path, sys.argv[1:3])
    lines = source_filepath.read_text(encoding="latin-1").splitlines()
    header = (
        f"Index of {source_filepath.name} (generated by stratagem.index_disassembly).\n"
        "Columns: address of the first instruction or data byte after the label, line number, label, comment.\n"
    )
    index_filepath.parent.mkdir(parents=True, exist_ok=True)
    index_filepath.write_text(header + "\n".join(index_lines(lines)) + "\n")


if __name__ == "__main__":
    main()
